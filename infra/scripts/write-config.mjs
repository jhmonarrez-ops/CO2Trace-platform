// Turns `cdk deploy --outputs-file outputs.json` into co2trace.config.js for the website.
// All values are public identifiers (no secrets); the site reads window.CO2TRACE_CONFIG.
import { readFileSync, writeFileSync } from 'node:fs';
const stage = process.argv[2] || 'prod';
const out = JSON.parse(readFileSync(new URL('../outputs.json', import.meta.url)))[`CO2Trace-${stage}`];
if (!out) throw new Error(`No outputs for CO2Trace-${stage}; run: npx cdk deploy -c stage=${stage} --outputs-file outputs.json`);
const cfg = { region: out.Region, apiUrl: out.ApiUrl, userPoolId: out.UserPoolId, clientId: out.UserPoolClientId, authDomain: out.AuthDomain };
const target = new URL(stage === 'prod' ? '../../co2trace.config.js' : `../../co2trace.config.${stage}.js`, import.meta.url);
writeFileSync(target, `// Generated by infra/scripts/write-config.mjs from the ${stage} stack outputs. Public values only.\nwindow.CO2TRACE_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`);
console.log('wrote', target.pathname);
