#!/usr/bin/env python3
"""Write docs/code-map.md: a line-numbered index of index.html (sections, ids,
CSS blocks, functions, top-level constants) so agents can jump to line ranges
instead of reading the whole 850 KB page. Run: python3 tools/dev/code_map.py"""
import re, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "index.html").read_text(encoding="utf-8").splitlines()

css, html, js, consts = [], [], [], []
re_css = re.compile(r"^\s*/\* ([^*]{3,80}?) \*/\s*$")
re_sec = re.compile(r"<(section|footer|dialog|header|nav|aside)\b[^>]*\bid=\"([^\"]+)\"")
re_fn = re.compile(r"^\s*(?:async\s+)?function\s+([A-Za-z_$][\w$]*)\s*\(")
re_arrow = re.compile(r"^\s*(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?(?:\([^)]*\)|[A-Za-z_$][\w$]*)\s*=>")
re_const = re.compile(r"^\s{0,2}(?:const|let)\s+([A-Z][A-Z0-9_]{1,})\s*=")
in_script = False
for n, line in enumerate(src, 1):
    if "<script" in line and "src=" not in line: in_script = True
    if "</script>" in line: in_script = False
    if len(line) > 400 and not re_fn.match(line):  # long data lines: only note constants
        m = re_const.match(line)
        if m: consts.append((n, m.group(1) + f" (long line, {len(line)} chars)"))
        continue
    if not in_script:
        m = re_css.match(line)
        if m: css.append((n, m.group(1)))
        for m in re_sec.finditer(line): html.append((n, f"<{m.group(1)} #{m.group(2)}>"))
    else:
        m = re_fn.match(line) or re_arrow.match(line)
        if m: js.append((n, m.group(1)))
        else:
            m = re_const.match(line)
            if m: consts.append((n, m.group(1)))

out = [f"# index.html code map ({len(src)} lines)", "",
       "Generated by `tools/dev/code_map.py`; regenerate after editing index.html. "
       "Never read index.html whole: grep for a name, then read about 80 lines around the line number.", ""]
def block(title, rows, per=4):
    out.append(f"## {title}")
    cells = [f"{n} {name}" for n, name in rows]
    for i in range(0, len(cells), per): out.append(" · ".join(cells[i:i + per]))
    out.append("")
block("HTML sections and dialogs (line #id)", html, 3)
block("CSS blocks", css, 3)
block("Top-level constants", consts, 5)
block("JS functions", js, 6)
(root / "docs" / "code-map.md").write_text("\n".join(out), encoding="utf-8")
print(f"code-map: {len(html)} sections, {len(css)} css, {len(consts)} consts, {len(js)} functions")
